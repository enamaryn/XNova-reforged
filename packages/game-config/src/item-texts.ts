/** Textes d'un élément dans la langue demandée ; le français (ou un identifiant inconnu) retombe sur `fallback`. */
export function localizeItem(
  id: number,
  locale: string | null | undefined,
  fallback: { name: string; description?: string },
): { name: string; description: string } {
  const entry =
    locale && locale !== "fr" && isSupportedLocale(locale) ? ITEM_TEXTS[locale as Exclude<SupportedLocale, "fr">]?.[id] : undefined;
  return {
    name: entry?.[0] ?? fallback.name,
    description: entry?.[1] ?? fallback.description ?? "",
  };
}

/** Identifiants couverts (pour le test de complétude). */
export const LOCALIZED_ITEM_IDS: readonly number[] = Object.keys(EN).map(Number);
export const LOCALIZED_LOCALES = ["en", "es", "de", "it"] as const;
export function itemTextsFor(locale: (typeof LOCALIZED_LOCALES)[number]): Record<number, ItemText> {
  return ITEM_TEXTS[locale];
}
